const btn = document.getElementById('btn');
const result = document.getElementById('result');
const counter = document.getElementById('counter');
const memes = document.getElementById('memes');
const secret = document.getElementById('secret');
const closeSecret = document.getElementById('closeSecret');

let clicks = 0;
let loadedMb = 0;
let expectedMb = 300;

const SECRET_CHANCE = 0.000001; // 0.0001% = 1 из 1 000 000

// 3 файла по ~99 МБ = ~297 МБ
const DATA_FILES = ['data1.bin', 'data2.bin', 'data3.bin'];

DATA_FILES.forEach(file => {
  fetch(file)
    .then(r => r.blob())
    .then(blob => {
      loadedMb += blob.size / (1024 * 1024);
      memes.textContent = `📦 ${loadedMb.toFixed(1)} / ${expectedMb} МБ мемов`;
      counter.textContent = `кликов: ${clicks} · мемов на сайте: ${loadedMb.toFixed(1)} / ${expectedMb} МБ`;
    })
    .catch(() => {});
});

btn.addEventListener('click', () => {
  clicks++;
  counter.textContent = `кликов: ${clicks} · мемов на сайте: ${loadedMb.toFixed(1)} / ${expectedMb} МБ`;

  if (Math.random() < SECRET_CHANCE) {
    secret.style.display = 'flex';
    return;
  }

  const text = actions[Math.floor(Math.random() * actions.length)];
  result.classList.remove('fade');
  void result.offsetWidth;
  result.textContent = text;
  result.classList.add('fade');
});

closeSecret.addEventListener('click', () => {
  secret.style.display = 'none';
});